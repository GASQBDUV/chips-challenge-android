#!/usr/bin/env python3
"""Generate src/tile_tt.h from re/tile_tables.txt: TT[tile] = {chipClass,chipKind,blockClass,blockKind,monClass,monKind}."""
import re
rows = {}
for line in open('re/tile_tables.txt'):
    m = re.match(r'0x([0-9a-f]+)\s+.*?\|\s*(\d),(\d)\s*\|\s*(\d),(\d)\s*\|\s*(\d),(\d)', line)
    if m: rows[int(m.group(1), 16)] = [int(m.group(i)) for i in range(2, 8)]
out = ['/* generated by tools/gen_tt.py from the reverse-engineered tile tables */', 'static const unsigned char TT[0x70][6] = {']
for t in range(0x70): out.append('  {%s}, /* %02x */' % (','.join(map(str, rows.get(t, [0]*6))), t))
out.append('};')
open('src/tile_tt.h', 'w').write('\n'.join(out) + '\n'); print(len(rows), 'tiles')
