#!/usr/bin/env python3
"""Generate src/font_data.h: ASCII 32..126 proportional antialiased glyphs from Pillow's built-in default font (Aileron, CC0)."""
import sys
from PIL import Image, ImageDraw, ImageFont
size = int(sys.argv[2]) if len(sys.argv) > 2 else 11
f = ImageFont.load_default(size=size)
asc, desc = f.getmetrics(); H = asc + desc + 1
out = ['/* generated by tools/mkfont.py: Pillow default font (Aileron, CC0) */', '#define FONT_H %d' % H, '#define FONT_ASC %d' % asc]
widths = []; data = []
for c in range(32, 127):
    ch = chr(c); adv = int(round(f.getlength(ch))) or 3
    w = max(adv, 1)
    im = Image.new('L', (w + 2, H), 0); ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=255)
    widths.append(w + 0); data.append(list(im.crop((0, 0, w, H)).tobytes()))
out.append('static const unsigned char font_w[95] = {%s};' % ','.join(map(str, widths)))
out.append('static const unsigned char font_d[] = {')
for d in data: out.append(','.join(map(str, d)) + ',')
out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print('H', H, 'asc', asc)
